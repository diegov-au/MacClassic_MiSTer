module ps2_kbd
(
	input	clk,
	input	ce,

	input			 reset,

	input [10:0] ps2_key,
	output reg   capslock,

	input  [7:0] data_out,
	input			 strobe_out,

	output [7:0] data_in,
	output 		 strobe_in
);

reg   [9:0] keymac;
reg			key_pending;
reg  [19:0] pacetimer;
reg			inquiry_active;
reg 			cmd_inquiry;
reg 			cmd_instant;
reg 			cmd_model;
reg 			cmd_test;

always@(posedge clk or posedge reset) begin
	if (reset) begin
		cmd_inquiry <= 0;
		cmd_instant <= 0;
		cmd_model <= 0;
		cmd_test <= 0;
	end else if(ce) begin
		if (strobe_out) begin
			cmd_inquiry <= 0;
			cmd_instant <= 0;
			cmd_model <= 0;
			cmd_test <= 0;
			case(data_out)
				8'h10: cmd_inquiry <= 1;
				8'h14: cmd_instant <= 1;
				8'h16: cmd_model   <= 1;
				8'h36: cmd_test    <= 1;
			endcase
		end
	end
end

always@(posedge clk or posedge reset) begin
	if (reset)
		pacetimer <= 0;
	else if(ce) begin

		if (strobe_out)
			pacetimer <= 0;
		else if (!tick_long)
			pacetimer <= pacetimer + 1'd1;
	end
end

wire tick_long  = pacetimer == 20'hfffff;
wire tick_short = pacetimer == 20'h00fff;

always@(posedge clk or posedge reset) begin
	if (reset)
		inquiry_active <= 0;
	else if(ce) begin
		if (strobe_out | strobe_in)
			inquiry_active <= 0;
		else if (tick_short)
			inquiry_active <= cmd_inquiry;
	end
end

wire pop_key = (cmd_instant & tick_short) | (inquiry_active & tick_long) | (inquiry_active & key_pending);

assign strobe_in = ((cmd_model | cmd_test) & tick_short) | pop_key;

assign data_in = cmd_test 	  ? 8'h7d :
		           cmd_model	  ? 8'h0b :
		           key_pending ? (keymac[9] ? {keymac[7],7'h71} : keymac[8] ? 8'h79 : keymac[7:0]) :
		                         8'h7b;

wire press        = ps2_key[9];
wire capslock_key = (ps2_key[8:0] == 'h58);

always @(posedge clk) begin
	reg old_stb;

	if(ce) begin
		old_stb <= ps2_key[10];
		if(old_stb != ps2_key[10]) begin

			if(capslock_key && press) capslock <= ~capslock;

			if(!key_pending && !(capslock_key && capslock)) begin
				key_pending <= 1;
				keymac <= {key_code[9:8],~press,key_code[6:0]};
			end
		end

		if (pop_key) begin
			if (keymac[9]) keymac[9] <= 0;
			else if (keymac[8]) keymac[8] <= 0;
			else key_pending <= 0;
		end
	end

	if (cmd_model | cmd_test | reset) key_pending <= 0;
	if (reset) capslock <= 0;
end

